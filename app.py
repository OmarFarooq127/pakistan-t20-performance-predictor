def venue_to_home(venue: str) -> int:
    """Infer if Pakistan is at home based on venue."""
    venue_lower = (venue or "").lower()
    pak_venues = ["karachi", "lahore", "rawalpindi", "multan", "islamabad"]
    return 1 if any(x in venue_lower for x in pak_venues) else 0


@st.cache_data
def load_data():
    player = pd.read_csv(OUT / "player_match_pi.csv", parse_dates=["Date"])
    team = pd.read_csv(OUT / "team_match_aggregates.csv", parse_dates=["Date"])
    country = pd.read_csv(OUT / "country_baseline.csv")
    preds = pd.read_csv(OUT / "pre_match_predictions.csv", parse_dates=["Date"])
    return player, team, country, preds


@st.cache_resource
def load_models():
    paths = {
        "Pred_Bat_PI": OUT / "layer2_pred_bat_pi.pkl",
        "Pred_Bowl_PI": OUT / "layer2_pred_bowl_pi.pkl",
        "Pred_Field_PI": OUT / "layer2_pred_field_pi.pkl",
    }
    models = {}
    for key, path in paths.items():
        if path.exists():
            try:
                models[key] = joblib.load(path)
            except Exception:
                models[key] = None
        else:
            models[key] = None
    return models


@st.cache_data
def build_player_lookup(player: pd.DataFrame):
    pak = player[player["Team"] == "Pakistan"].copy()
    pak = pak.sort_values("Date")
    latest = pak.groupby("Player").tail(1)
    defaults = {
        "Bat_Form": pak["Bat_Form"].mean(skipna=True),
        "Bowl_Form": pak["Bowl_Form"].mean(skipna=True),
        "Field_Form": pak["Field_Form"].mean(skipna=True),
    }
    return latest.set_index("Player"), defaults


def assemble_feature_row(
    squad: list,
    opponent: str,
    chase: int,
    toss_win: int,
    home_adv: int,
    pitch: dict,
    player_lookup: pd.DataFrame,
    player_defaults: dict,
    country_df: pd.DataFrame,
    team_latest: pd.DataFrame = None,
):
    bat_forms = []
    bowl_forms = []
    field_forms = []

    for p in squad:
        if p in player_lookup.index:
            row = player_lookup.loc[p]
            bat_forms.append(row.get("Bat_Form", player_defaults["Bat_Form"]))
            bowl_forms.append(row.get("Bowl_Form", player_defaults["Bowl_Form"]))
            field_forms.append(row.get("Field_Form", player_defaults["Field_Form"]))
        else:
            bat_forms.append(player_defaults["Bat_Form"])
            bowl_forms.append(player_defaults["Bowl_Form"])
            field_forms.append(player_defaults["Field_Form"])

    def top_k_sum(values, k):
        if not values:
            return 0.0
        vals = sorted([v for v in values if pd.notna(v)], reverse=True)
        return float(sum(vals[:k])) if vals else 0.0

    feature_row = {
        "Team_Bat_Form": float(sum([v for v in bat_forms if pd.notna(v)])) if bat_forms else 0.0,
        "Team_Bowl_Form": float(sum([v for v in bowl_forms if pd.notna(v)])) if bowl_forms else 0.0,
        "Team_Field_Form": float(sum([v for v in field_forms if pd.notna(v)])) if field_forms else 0.0,
        "Top3_Bat_Form_Sum": top_k_sum(bat_forms, 3),
        "Top2_Bowl_Form_Sum": top_k_sum(bowl_forms, 2),
        "Pace_Bounce": pitch["Pace_Bounce"],
        "Seam_Swing": pitch["Seam_Swing"],
        "Spin_Potential": pitch["Spin_Potential"],
        "Abrasion_Rate": pitch["Abrasion_Rate"],
        "Soil_Type": pitch["Soil_Type"],
        "Toss_Win": int(toss_win),
        "Chase": int(chase),
        "Home_Advantage": int(home_adv),
    }

    opp_row = country_df[country_df["Team"] == opponent].head(1)
    if opp_row.empty:
        opp_avg = {
            "Opp_WL_Ratio": float(country_df["WL_Ratio"].mean()),
            "Opp_Avg_Bat_PI": float(country_df["Avg_Bat_PI"].mean()),
            "Opp_Avg_Bowl_PI": float(country_df["Avg_Bowl_PI"].mean()),
            "Opp_Avg_Field_PI": float(country_df["Avg_Field_PI"].mean()),
        }
    else:
        opp_avg = {
            "Opp_WL_Ratio": float(opp_row["WL_Ratio"].iloc[0]),
            "Opp_Avg_Bat_PI": float(opp_row["Avg_Bat_PI"].iloc[0]),
            "Opp_Avg_Bowl_PI": float(opp_row["Avg_Bowl_PI"].iloc[0]),
            "Opp_Avg_Field_PI": float(opp_row["Avg_Field_PI"].iloc[0]),
        }

    # Opponent recent form (last-10), from latest team aggregates table
    opp_form = {}
    if isinstance(team_latest, pd.DataFrame) and not team_latest.empty and opponent in team_latest.index:
        r = team_latest.loc[opponent]
        opp_form = {
            "Opp_Bat_Form": float(r.get("Team_Bat_Form", pd.NA)) if pd.notna(r.get("Team_Bat_Form", pd.NA)) else float(team_latest.get("Team_Bat_Form").mean()),
            "Opp_Bowl_Form": float(r.get("Team_Bowl_Form", pd.NA)) if pd.notna(r.get("Team_Bowl_Form", pd.NA)) else float(team_latest.get("Team_Bowl_Form").mean()),
            "Opp_Field_Form": float(r.get("Team_Field_Form", pd.NA)) if pd.notna(r.get("Team_Field_Form", pd.NA)) else float(team_latest.get("Team_Field_Form").mean()),
        }
    else:
        # Fallback to overall mean of forms if opponent not present
        if isinstance(team_latest, pd.DataFrame) and not team_latest.empty:
            opp_form = {
                "Opp_Bat_Form": float(team_latest.get("Team_Bat_Form").mean()),
                "Opp_Bowl_Form": float(team_latest.get("Team_Bowl_Form").mean()),
                "Opp_Field_Form": float(team_latest.get("Team_Field_Form").mean()),
            }
        else:
            # last resort: use country averages as a weak proxy
            opp_form = {
                "Opp_Bat_Form": float(country_df["Avg_Bat_PI"].mean()),
                "Opp_Bowl_Form": float(country_df["Avg_Bowl_PI"].mean()),
                "Opp_Field_Form": float(country_df["Avg_Field_PI"].mean()),
            }

    feature_row.update(opp_avg)
    feature_row.update(opp_form)
    return pd.DataFrame([feature_row])

