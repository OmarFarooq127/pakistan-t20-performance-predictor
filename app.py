"""
Streamlit frontend for Pakistan T20 Performance Intelligence.
Displays verification metrics, country baselines, team aggregates, and pre-match predictions.
Requires outputs generated by running `python pipeline.py` first.
"""
import pathlib
import pandas as pd
import streamlit as st
import plotly.express as px

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "outputs"

# Popular cricketing nations for focused views
POPULAR_COUNTRIES = [
    "India",
    "Australia",
    "England",
    "Pakistan",
    "South Africa",
    "New Zealand",
    "Sri Lanka",
    "Bangladesh",
    "West Indies",
    "Afghanistan",
]

@st.cache_data
def load_data():
    player = pd.read_csv(OUT / "player_match_pi.csv", parse_dates=["Date"])
    team = pd.read_csv(OUT / "team_match_aggregates.csv", parse_dates=["Date"])
    country = pd.read_csv(OUT / "country_baseline.csv")
    preds = pd.read_csv(OUT / "pre_match_predictions.csv", parse_dates=["Date"])
    return player, team, country, preds

player_df, team_df, country_df, preds_df = load_data()

st.set_page_config(page_title="Pakistan T20 PI Dashboard", layout="wide")
st.title("Pakistan T20 Performance Intelligence")
st.caption("Powered by pipeline.py outputs. Run the pipeline before launching.")

# Layer 1 verification metrics
st.subheader("Layer 1: PI → Win Verification")
try:
    metrics = pd.read_json(OUT / "layer1_metrics.json")
    c1, c2, c3 = st.columns(3)
    c1.metric("Accuracy", f"{metrics['accuracy'][0]:.3f}")
    c2.metric("Precision", f"{metrics['precision'][0]:.3f}")
    c3.metric("Recall", f"{metrics['recall'][0]:.3f}")
except Exception:
    st.warning("layer1_metrics.json missing or unreadable.")

st.divider()

# Layer 2 metrics
st.subheader("Layer 2: Pre-Match Predictor Performance")
try:
    l2 = pd.read_json(OUT / "layer2_metrics.json")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Accuracy", f"{l2['accuracy'][0]:.3f}")
    c2.metric("Precision", f"{l2['precision'][0]:.3f}")
    c3.metric("Recall", f"{l2['recall'][0]:.3f}")
    c4.metric("MAE (Bat/Bowl/Field)", f"{l2['mae_pred_bat'][0]:.1f} / {l2['mae_pred_bowl'][0]:.1f} / {l2['mae_pred_field'][0]:.1f}")
except Exception:
    st.warning("layer2_metrics.json missing or unreadable.")
 
st.divider()

# Country baselines
st.subheader("Country Baseline Table")

show_popular_only = st.checkbox("Show popular countries only", value=True)

df_baseline = country_df.copy()
if show_popular_only:
    df_baseline = df_baseline[df_baseline["Team"].isin(POPULAR_COUNTRIES)]
    # Sort by Matches desc, then WL ratio desc
    df_baseline = df_baseline.sort_values(["Matches", "WL_Ratio"], ascending=[False, False])
else:
    # Put popular countries at the top, then sort by Matches desc and WL ratio
    df_baseline["_popular_first"] = df_baseline["Team"].apply(lambda x: 0 if x in POPULAR_COUNTRIES else 1)
    df_baseline = df_baseline.sort_values(["_popular_first", "Matches", "WL_Ratio"], ascending=[True, False, False])
    df_baseline.drop(columns=["_popular_first"], inplace=True)

st.dataframe(df_baseline, height=300)

st.divider()

# Team aggregates summary
st.subheader("Team Aggregate PIs")

# Toggle to focus on major countries
major_only = st.checkbox("Major Countries Only", value=True)

latest_team = team_df.sort_values("Date", ascending=False).groupby("Team").head(1)
if major_only:
    latest_team = latest_team[latest_team["Team"].isin(POPULAR_COUNTRIES)]
    latest_team = latest_team.sort_values(["Matches" if "Matches" in latest_team.columns else "Date", "Winner"], ascending=[False, False])
else:
    # Put major teams first, then sort by matches/date
    latest_team["_popular_first"] = latest_team["Team"].apply(lambda x: 0 if x in POPULAR_COUNTRIES else 1)
    latest_team = latest_team.sort_values(["_popular_first", "Matches" if "Matches" in latest_team.columns else "Date"], ascending=[True, False])
    latest_team.drop(columns=["_popular_first"], inplace=True)

st.dataframe(latest_team[[
    "Team", "WL_Ratio" if "WL_Ratio" in latest_team.columns else "Winner", "Team_Bat_PI", "Team_Bowl_PI", "Team_Field_PI",
    "Team_Bat_Form", "Team_Bowl_Form", "Team_Field_Form"
]], height=300)

st.divider()

# Pre-match predictor exploration
st.subheader("Layer 2: Pakistan Pre-Match Predictions")
if preds_df.empty:
    st.warning("No pre_match_predictions.csv found. Run pipeline first.")
else:
    preds_df = preds_df.sort_values("Date")
    opps_all = sorted(preds_df["Opponent"].dropna().unique())
    filter_pop_opp = st.checkbox("Popular opponents only", value=True)
    if filter_pop_opp:
        opps = [o for o in opps_all if o in POPULAR_COUNTRIES]
        if not opps:
            opps = opps_all
    else:
        opps = opps_all
    sel_opp = st.selectbox("Opponent", options=opps)
    filtered = preds_df[preds_df["Opponent"] == sel_opp].copy()
    if filtered.empty:
        st.info("No rows for this opponent.")
    else:
        latest = filtered.iloc[-1]
        cols = st.columns(5)
        cols[0].metric("Pred Bat PI", f"{latest['Pred_Bat_PI']:.1f}")
        cols[1].metric("Pred Bowl PI", f"{latest['Pred_Bowl_PI']:.1f}")
        cols[2].metric("Pred Field PI", f"{latest['Pred_Field_PI']:.1f}")
        cols[3].metric("Opponent Avg PI", f"{latest['Opp_Total_PI']:.1f}")
        win_text = "Yes" if latest.get("Pred_Win", 0) == 1 else "No"
        cols[4].metric("Predicted Win?", win_text)

        st.markdown("**Match history vs selected opponent**")
        show_cols = [
            "Date", "Match_ID", "Pred_Total_PI", "Opp_Total_PI", "Environmental_Weight",
            "Pred_Win", "Winner", "Top3_Bat_Form_Sum", "Top2_Bowl_Form_Sum", "Chase", "Toss_Win", "Home_Advantage"
        ]
        show_cols = [c for c in show_cols if c in filtered.columns]
        st.dataframe(filtered[show_cols].tail(30), height=360)

        # Trend plot of predicted total PI vs opponent baseline
        fig = px.line(
            filtered,
            x="Date",
            y=["Pred_Total_PI", "Opp_Total_PI"],
            labels={"value": "PI", "variable": "Series"},
            title="Predicted Total PI vs Opponent Baseline",
        )
        st.plotly_chart(fig, use_container_width=True)

st.divider()

st.caption("Tip: Re-run pipeline.py to refresh outputs, then reload this page.")
